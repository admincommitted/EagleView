  freightDashboard: (kind) => getData('/freight/dashboard', { params: { kind } }),
  recordFreightEvent: (event) => postData('/freight/events', event),
  generateAwbPdf: (html, filename) => postData('/awb/generate-pdf', { html, filename }, { responseType: 'blob' }),
