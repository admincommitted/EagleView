  chargeMaster: () => getData('/masters/charges'),
  specialHandlingMaster: () => getData('/masters/specialhandlingcodes'),
  availableHawbStock: () => getData('/stock/hawb/list', { params: { status: 'AVAILABLE' } }),
  nextAwbFromStock: (prefix) => getData(`/stock/next/${prefix}`),
  awbStockSuggestions: (params) => getData('/stock/list', { params }),
  awbByNumber: (awbNumber) => getData(`/awb/search/${awbNumber}`),
