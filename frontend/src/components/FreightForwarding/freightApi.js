  hawbByNumber: (awbNumber) => getData('/awb/hawb', { params: { awbNumber } }),
  linkHawbToMaster: async (hawbId, master) => (await axiosInstance.patch(`/awb/hawb/${hawbId}/link`, master)).data,
  airportList: () => getData('/locations/airports'),
